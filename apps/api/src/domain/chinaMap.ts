// Coordinates are approximate modern locations; borders are a game extent, not sovereignty claims.
export type MapPoint = [number, number];
export const project = (longitude: number, latitude: number): MapPoint => [
  Number(((longitude - 111) * 1.12).toFixed(3)), Number(((32 - latitude) * 1.3).toFixed(3)),
];
const line = (points: MapPoint[]) => points.map(([lon, lat]) => project(lon, lat));
export function onLand(x: number, z: number): boolean {
  const polygon = CHINA_MAP.outline;
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const a = polygon[i]!, b = polygon[j]!;
    if ((a[1] > z) !== (b[1] > z) && x < (b[0]-a[0])*(z-a[1])/(b[1]-a[1])+a[0]) inside = !inside;
  }
  return inside;
}
