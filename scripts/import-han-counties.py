"""Import the factual Eastern Han administrative register, preserving source names.

Usage: python3 scripts/import-han-counties.py /tmp/arena-han-counties.html
Source: https://zh.wikipedia.org/wiki/东汉行政区划 (administrative list table).
This is an Eastern Han register, NOT a verified complete AD 190 time slice.
County coordinates are deliberately not invented by this importer.
"""
from html.parser import HTMLParser
from pathlib import Path
import json
import re
import sys

class TableParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tables, self.table, self.row, self.cell = [], None, None, None
        self.depth = 0
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'table':
            self.depth += 1
            if self.depth == 1: self.table = []
        if self.depth != 1: return
        if tag == 'tr': self.row = []
        if tag in ('td', 'th'): self.cell = []
        if tag == 'br' and self.cell is not None: self.cell.append(' ')
    def handle_data(self, data):
        if self.depth == 1 and self.cell is not None: self.cell.append(data)
    def handle_endtag(self, tag):
        if self.depth == 1:
            if tag in ('td', 'th') and self.cell is not None:
                self.row.append(''.join(self.cell).strip())
                self.cell = None
            if tag == 'tr' and self.row is not None:
                self.table.append(self.row)
                self.row = None
            if tag == 'table': self.tables.append(self.table)
        if tag == 'table': self.depth -= 1

parser = TableParser()
parser.feed(Path(sys.argv[1]).read_text())
table = next(t for t in parser.tables if any('下轄縣' in ' '.join(r) for r in t))
records, province = [], ''
for row in table:
    if len(row) == 6:
        province = re.split('[（(]', row[0])[0].strip()
        row = row[2:]
    if len(row) != 4 or not row[1].isdigit(): continue
    county_names = [re.sub(r'\[[^\]]*\]', '', s).strip() for s in re.split('[、，]', row[3])]
    county_names = [s for s in county_names if s]
    records.append({'province': province, 'name': row[0], 'seat': row[2],
                    'reportedCount': int(row[1]), 'counties': county_names})
assert len(records) > 90, f'Unexpected commandery count: {len(records)}'
assert sum(len(r['counties']) for r in records) > 1000
target = Path(__file__).resolve().parents[1] / 'apps/api/src/domain/hanRegister.ts'
target.write_text('// Generated by scripts/import-han-counties.py. See data/han-map-sources.md.\n'
                  + 'export const HAN_REGISTER = ' + json.dumps(records, ensure_ascii=False, indent=2) + ';\n')
print(json.dumps({'commanderies': len(records), 'counties': sum(len(r['counties']) for r in records),
                  'provinces': sorted(set(r['province'] for r in records)),
                  'countDifferences': [r['name'] for r in records if len(r['counties']) != r['reportedCount']]}, ensure_ascii=False))
print(' '.join(r['name'] for r in records))
